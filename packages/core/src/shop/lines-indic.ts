/** Adds these languages to an existing line bank. */
export function withIndicLines(bank: LineBank): LineBank {
  const out: LineBank = { ...bank };
  for (const [lang, lines] of Object.entries(T)) {
    for (const [id, text] of Object.entries(lines)) out[id] = { ...out[id], [lang]: [text] };
  }
  return out;
}
